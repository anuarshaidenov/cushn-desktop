const toWords = (text: string) =>
  text
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);

export const ICON_GROUPS: CatalogIconGroup[] = BUDGET_ICON_GROUPS.map(
  (group) => ({
    label: group.label,
    items: group.icons.map(({ name, label, keywords }) => ({
      name,
      label,
      svg: SVGS[name],
      terms: [...new Set(toWords(`${label} ${keywords} ${group.label}`))],
    })),
  }),
);

const ICONS_BY_NAME = new Map<string, CatalogIcon>(
  ICON_GROUPS.flatMap((g) => g.items).map((icon) => [icon.name, icon]),
);

export const findIcon = (name: string | null | undefined) =>
  name ? ICONS_BY_NAME.get(name) : undefined;

export const matchesIconQuery = (icon: CatalogIcon, query: string) =>
  toWords(query).every((word) =>
    icon.terms.some((term) => term.startsWith(word)),
  );
