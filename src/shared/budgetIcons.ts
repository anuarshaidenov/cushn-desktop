export type BudgetIconName = (typeof GROUPS)[number]["icons"][number][0];

export interface BudgetIcon {
  name: BudgetIconName;
  label: string;
  keywords: string;
}

export interface BudgetIconGroup {
  label: string;
  icons: BudgetIcon[];
}

export const BUDGET_ICON_GROUPS: readonly BudgetIconGroup[] = GROUPS.map((group) => ({
  label: group.label,
  icons: group.icons.map(([name, label, keywords]) => ({ name, label, keywords })),
}));

const names = new Set<string>(
  BUDGET_ICON_GROUPS.flatMap((group) => group.icons.map((icon) => icon.name)),
);

export const isBudgetIconName = (value: string): value is BudgetIconName => names.has(value);
